/** Curated objects. High-z distances are computed from the live cosmology. */

export function hours(h, m = 0, s = 0) {
  return 15 * (h + m / 60 + s / 3600);
}

export function degrees(d, m = 0, s = 0) {
  const sign = d < 0 ? -1 : 1;
  return sign * (Math.abs(d) + m / 60 + s / 3600);
}

export function skyToXyz(raDeg, decDeg, distance) {
  const ra = (raDeg * Math.PI) / 180;
  const dec = (decDeg * Math.PI) / 180;
  const cosDec = Math.cos(dec);
  return [
    distance * cosDec * Math.cos(ra),
    distance * Math.sin(dec),
    distance * cosDec * Math.sin(ra),
  ];
}

