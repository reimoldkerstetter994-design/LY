export function objectDistanceMpc(item, cosmo) {
  if (item.distanceMpc != null) return item.distanceMpc;
  if (item.z != null) return cosmo.chiOfZ(item.z);
  if (item.kpc) return Math.hypot(...item.kpc) / 1000;
  return 0;
}
